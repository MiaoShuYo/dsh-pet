/**
 * Repository checks: manifest shape, version sync, JS syntax, bundle freshness
 * and bundle wrapper invariants. Runs with no dependencies.
 *
 * Run with: node scripts/check.mjs
 */
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, extname, join, relative, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const failures = []

/**
 * Record a failed assertion.
 * @param message - failure text.
 * @returns undefined
 */
function fail(message) {
  failures.push(message)
}

/**
 * Read a repository file.
 * @param path - relative path.
 * @returns text.
 */
function read(path) {
  return readFileSync(resolve(ROOT, path), 'utf8').replace(/\r\n/g, '\n')
}

const pkg = JSON.parse(read('package.json'))
const constants = read('src/shared/constants.js')
const host = read('lib/index.js')
const patch = read('cordis.patch.yml')
const client = read('lib/client.js')

if (pkg.name !== 'dsh-pet') fail('package.json name must be dsh-pet')
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(pkg.version)) fail('package.json version is not semver')
if (pkg.type !== 'module') fail('package.json type must be module')
if (pkg.main !== 'lib/index.js') fail('package.json main must be lib/index.js')
if (!pkg.exports || pkg.exports['./client'] !== './lib/client.js') fail('package.json must export ./client')
if (!pkg.dsh || !pkg.dsh.bundle || pkg.dsh.bundle.patch !== './cordis.patch.yml') fail('package.json must declare dsh.bundle.patch')
if (!pkg.dsh || !pkg.dsh.client || pkg.dsh.client.platform !== 'web') fail('package.json must declare dsh.client.platform = web')
if (!pkg.engines || typeof pkg.engines.dsh !== 'string' || pkg.engines.dsh === '') fail('package.json must declare engines.dsh')
if (!pkg.files || !pkg.files.includes('lib') || !pkg.files.includes('cordis.patch.yml')) fail('package.json files must include lib and cordis.patch.yml')

const versionMatch = /export const PET_VERSION = '([^']+)'/.exec(constants)
if (versionMatch === null) fail('src/shared/constants.js must declare PET_VERSION')
else if (versionMatch[1] !== pkg.version) fail(`PET_VERSION ${versionMatch[1]} does not match package version ${pkg.version}`)

if (!/export const name = 'dsh-pet'/.test(host)) fail('lib/index.js must export name = dsh-pet')
if (!/name: 'dsh-pet'/.test(patch)) fail('cordis.patch.yml must mount dsh-pet')

if (!client.startsWith('/* Generated by scripts/build-client.mjs')) fail('lib/client.js must be generated by the build script')
if (!client.includes('id: "dsh-pet"')) fail('lib/client.js must carry the dsh-pet module id')
if (!client.includes('exports.apply = apply')) fail('lib/client.js must export apply')
if (!client.includes('exports.inject = inject')) fail('lib/client.js must export inject')
if (!client.includes("ctx.slots.inject('shell.overlay'")) fail('lib/client.js must register shell.overlay')
if (/^\s*import\s/m.test(client)) fail('lib/client.js must not contain import statements')
if (/^\s*export\s/m.test(client)) fail('lib/client.js must not contain export statements')

/**
 * Recursively list JS/MJS files outside node_modules.
 * @param directory - absolute directory.
 * @param output - accumulator.
 * @returns output.
 */
function listSources(directory, output = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
    const full = join(directory, entry.name)
    if (entry.isDirectory()) listSources(full, output)
    else if (extname(entry.name) === '.js' || extname(entry.name) === '.mjs') output.push(full)
  }
  return output
}

for (const file of listSources(ROOT)) {
  const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' })
  if (result.status !== 0) {
    fail(`syntax error in ${relative(ROOT, file)}\n${result.stderr || result.stdout || ''}`)
  }
}

const build = spawnSync(process.execPath, [resolve(ROOT, 'scripts/build-client.mjs'), '--check'], {
  cwd: ROOT,
  encoding: 'utf8',
})
if (build.status !== 0) fail((build.stderr || build.stdout || 'client bundle is stale').trim())

if (failures.length > 0) {
  console.error('checks failed:\n- ' + failures.join('\n- '))
  process.exit(1)
}
console.log(`checks passed (${pkg.name}@${pkg.version}, ${pkg.engines.dsh})`)
